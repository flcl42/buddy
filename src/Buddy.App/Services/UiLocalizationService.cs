using System.Globalization;

namespace Buddy.App.Services;

public sealed class UiLocalizationService
{
    private static readonly Dictionary<string, string> English =
        CreateEnglish();

    private static readonly Dictionary<string, string> Belarusian =
        CreateBelarusian();

    private static readonly Dictionary<string, string> Russian =
        CreateRussian();

    public string CurrentLanguageId { get; private set; } = "en";

    public event EventHandler? Changed;

    public string Get(string key)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(key);
        Dictionary<string, string> selected = GetDictionary(CurrentLanguageId);
        return selected.TryGetValue(key, out string? value)
            ? value
            : English.TryGetValue(key, out value)
                ? value
                : key;
    }

    public void Apply(string languageId)
    {
        Dictionary<string, string> selected = GetDictionary(languageId);
        CurrentLanguageId = languageId;
        CultureInfo culture = CultureInfo.GetCultureInfo(languageId switch
        {
            "be" => "be-BY",
            "ru" => "ru-RU",
            _ => "en-US",
        });
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
        if (Application.Current?.Resources is ResourceDictionary resources)
        {
            foreach ((string key, string value) in English)
            {
                resources[key] = selected.TryGetValue(key, out string? translation)
                    ? translation
                    : value;
            }
        }

        Changed?.Invoke(this, EventArgs.Empty);
    }

    private static Dictionary<string, string> GetDictionary(
        string languageId) => languageId switch
        {
            "be" => Belarusian,
            "ru" => Russian,
            _ => English,
        };

